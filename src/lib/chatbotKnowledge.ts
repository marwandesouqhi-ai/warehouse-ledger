/**
 * دالة لتنظيف وتوحيد الحروف العربية لتحقيق أعلى دقة بحث
 */
export function normalizeArabic(text: string): string {
  if (!text) return ''
  return text
    .toLowerCase()
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[\u064B-\u065F]/g, '') // إزالة التشكيل
    .trim()
}

/**
 * محرك البحث الذكي في بنك المعرفة:
 * يحسب درجات التطابق ويختار أفضل إجابة مطابقة أو يقترح بدائل
 */
export function findBestKnowledgeAnswer(query: string): {
  entry: KnowledgeEntry | null
  confidence: number
} {
  const cleanQuery = normalizeArabic(query)
  if (!cleanQuery) return { entry: null, confidence: 0 }

  let bestEntry: KnowledgeEntry | null = null
  let maxScore = 0

  for (const entry of KNOWLEDGE_BASE) {
    let score = 0

    // مطابقة الكلمات المفتاحية
    for (const kw of entry.keywords) {
      const cleanKw = normalizeArabic(kw)
      if (cleanQuery.includes(cleanKw)) {
        score += cleanKw.length * 2
      } else {
        const words = cleanKw.split(' ')
        for (const w of words) {
          if (w.length > 2 && cleanQuery.includes(w)) {
            score += w.length
          }
        }
      }
    }

    // مطابقة العنوان
    const cleanTitle = normalizeArabic(entry.title)
    if (cleanQuery.includes(cleanTitle)) {
      score += 15
    }

    if (score > maxScore) {
      maxScore = score
      bestEntry = entry
    }
  }

  return {
    entry: bestEntry,
    confidence: maxScore,
  }
}
